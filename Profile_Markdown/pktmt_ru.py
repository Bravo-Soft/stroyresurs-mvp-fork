# D88 (правило заказчика [[no-drawing-info-in-cards]]): на странице «Утепление запорной
# арматуры теплосетей» таблица размеров кожуха задана буквенными позициями-выносками
# (строки А, Б, В, … Л по столбцам моделей УЗА-001/УЗА-002) — это ЛЕГЕНДА сборочного
# чертежа. Сам чертёж в карточку товара не выводится, поэтому без него буквы бессмысленны.
# Вырезаем такую таблицу до извлечения.
#
# У pktmt.ru нет собственного extract() — товарные страницы идут через generic-конвертер и
# universal_extractor.extract_product_markdown (он парсит сырой HTML заново). Поэтому clean()
# должен примениться и на universal-пути — включаем флаг CLEAN_IN_UNIVERSAL (как chelaz D86).
CLEAN_IN_UNIVERSAL = True

import re
from bs4 import BeautifulSoup


def _is_drawing_legend_table(table) -> bool:
    """Таблица-ЛЕГЕНДА ЧЕРТЕЖА: размеры заданы буквенными выносками-позициями (А, Б, В…),
    расшифровываемыми ТОЛЬКО на чертеже. Без чертежа такая таблица нечитаема.
    Признак: хотя бы одна строка содержит >=3 ячеек, каждая из которых — ровно одна
    заглавная буква (кир./лат.). На запорной арматуре это строка-шапка «А|Б|В|…|Л»
    (столбцы моделей УЗА-001/УЗА-002). Обычные ТХ-таблицы pktmt (Параметр|Значение;
    Варианты со значениями-ЦИФРАМИ 1|2|3…) под правило НЕ попадают — цифры не буквы."""
    for r in table.find_all('tr'):
        cells = [c.get_text(' ', strip=True) for c in r.find_all(['td', 'th'])]
        if sum(1 for c in cells if re.fullmatch(r'[A-ZА-Я]', c or '')) >= 3:
            return True
    return False


def clean(soup: BeautifulSoup):
    """Упраздняет таблицу-легенду сборочного чертежа (буквенные позиции-выноски А/Б/В…):
    чертёж в карточку не выводится, а таблица размеров без него нечитаема. Остальные
    таблицы и контент страницы не затрагиваются."""
    for table in soup.find_all('table'):
        if _is_drawing_legend_table(table):
            try:
                table.decompose()
            except Exception:
                pass
