# На chelaz товарные страницы уходят по universal-пути (он парсит сырой HTML заново и
# НЕ вызывает доменные адаптеры). Просим universal_extractor всё же применить наш clean()
# к своему soup — иначе вырезание вкладки «Устройство …» не подействует (D86).
CLEAN_IN_UNIVERSAL = True

# Адаптер chelaz.ru (Челнинский арматурный завод).
#
# D86 (правило заказчика [[no-drawing-info-in-cards]], 08.07): вкладка «Устройство …»
# на карточке товара — это ЭКСПЛИКАЦИЯ деталей сборочного чертежа: нумерованный перечень
# позиций «Корпус / Крышка / Шпиндель / Диск / Гайка / Болт откидной / Шпилька / Прокладка /
# Штурвал / Сальник …» → материал/ГОСТ. Без самого чертежа (где эти позиции пронумерованы)
# перечень бессмысленен и в карточку товара попадать не должен. LLM затягивал его в поле
# description. Вырезаем панель этой вкладки и её ссылку-заголовок ДО конвертации в markdown.
#
# Что НЕ трогаем: сводку «Материал основных деталей» во вкладке «Технические характеристики»
# (отдельная таблица Параметр|Значение — самодостаточна, это полезные ТХ), общее описание,
# преимущества, таблицы размеров.

import re

# Вкладки на chelaz свёрстаны как <a href="...#N">Заголовок</a> + контент-панель
# <div id="N" class="kk-content">…</div>. Панель «Устройство …» начинается с этого заголовка.
_USTROJSTVO_RE = re.compile(r'^\s*Устройство\b', re.IGNORECASE)


def _is_ustrojstvo(text: str) -> bool:
    return bool(_USTROJSTVO_RE.match(text or ''))


def clean(soup):
    """Удаляет вкладку «Устройство …» (экспликация деталей чертежа) — панель и ссылку-заголовок.
    Возвращает число удалённых узлов (для логов/тестов)."""
    removed = 0
    # 1) контент-панель вкладки: div.kk-content, чей текст начинается с «Устройство …»
    for panel in soup.find_all('div', class_='kk-content'):
        if _is_ustrojstvo(panel.get_text(' ', strip=True)):
            panel.decompose()
            removed += 1
    # 2) ссылка-вкладка «Устройство …» в навигации (иначе останется висячий заголовок без контента)
    for a in soup.find_all('a'):
        if _is_ustrojstvo(a.get_text(' ', strip=True)):
            parent = a.parent
            a.decompose()
            if parent is not None and parent.name in ('li', 'p') and not parent.get_text(strip=True):
                parent.decompose()
            removed += 1
    return removed
