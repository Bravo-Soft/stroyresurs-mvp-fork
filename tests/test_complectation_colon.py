def test_component_quantity_has_colon(value, expected):
    generator = DOCXGenerator()
    doc = Document()
    # Количество проверяем внутри настоящего перечня из нескольких элементов.
    other_items = '\n- Прокладка;\n- Крышка;'
    generator._add_generic_field(doc, 'Комплектация', value + other_items)
    assert doc.paragraphs[2].text == expected + other_items
    repeated = Document()
    generator._add_generic_field(repeated, 'Комплектация', expected + other_items)
    assert repeated.paragraphs[2].text == expected + other_items


@pytest.mark.parametrize('value', [
    'Разъемное соединение «под вклейку» - 2 шт.: 1 шт.',
    'Уплотнительное кольцо разъемного соединения - 2 шт.: 1 шт.',
])
def test_user_confirmed_quantity_in_name_is_preserved(value):
    assert DOCXGenerator()._normalize_complectation_text(value) == value


def test_card_changes_only_complectation_and_preserves_source(tmp_path):
    generator = DOCXGenerator()

    async def no_rtf(path):
        return None

    generator._convert_to_rtf = no_rtf
    value = '- Блоков в поддоне 100 шт.;\n- Блоков в м^3 53,33 шт.;'
    data = {'product_id': 'test', 'source_url': 'https://example.ru/block/',
            'json_data': {'product': {
                'product_name': 'Блок перегородочный D500 (АэроБел)',
                'specifications': {'Размеры, мм': '625х150х200'},
                'description': 'На поддоне 100 шт.',
                'complectation': value,
                'advantages': value,
            }}}
    original = deepcopy(data)
    path = asyncio.run(generator.generate_product_card(data, {}, str(tmp_path)))
    doc = Document(path)
    paragraphs = [p.text for p in doc.paragraphs]
    assert '- Блоков в поддоне: 100 шт.;\n- Блоков в м^3: 53,33 шт.;' in paragraphs
    assert value in paragraphs
    assert 'На поддоне 100 шт.' in paragraphs
    assert data == original

